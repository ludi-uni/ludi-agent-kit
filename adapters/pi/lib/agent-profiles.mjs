// Native (pi-subagents) agent profiles derived from the common kit agents.
//
// Problem: pi-subagents treats an agent's `tools:` frontmatter as a strict
// allowlist only — it never interprets the kit's `access:` metadata. A child
// launched directly (subagent({agent:'coder'|'tester'}), /subagents, chained
// children) therefore gets read/write-style builtins but no shell at all:
// raw `powershell`/`bash` are deliberately never granted, and `ludi_exec` in
// the allowlist is meaningless unless its provider extension is loaded.
//
// Approved scope of this adaptation: ONLY the coder and tester roles (the
// parent-approved subagent workers) get tool/provider completion. Every other
// role keeps its source `tools:` frontmatter verbatim — including legacy
// `powershell` entries — and gains no provider. pi-subagents then treats those
// roles exactly as the common definitions wrote them; the orchestrator-path
// access policy (`lib/orchestrator/permissions.mjs`) still governs kit
// launches and is unaffected by this file.
//
// Derivation rules:
//   - Body is copied verbatim (no adapter detail is injected into prompts).
//   - Frontmatter is preserved; `tools`, `subagentOnlyExtensions`, and a
//     generated-from marker are the only keys ever rewritten.
//   - For coder/tester only: `tools` is rewritten via piToolsForAccess so the
//     allowlist gains `ludi_exec`, and `subagentOnlyExtensions` points at a
//     generated policy-explicit shell-gate wrapper (see
//     ../shell-gate/index.js). Their `access:` block remains the pinned
//     provider contract the wrapper embeds.
//   - Every other role keeps `tools` exactly as authored and gets no
//     extension, so no new tool permissions are ever added to browser,
//     reviewer, scout, visual, design-planner, or orchestrator profiles.
//
// The provider wrapper is generated per adapted profile into
// out/agent-profiles/extensions/<role>-shell-gate.mjs and embeds the role's
// access as fixed JSON (createShellGate({shell,network}); immutable per run,
// never ambient env).
//
// Publish safety: the renderer never deletes existing output before the new
// generation is fully built. All candidates are parsed and derived up front,
// every file is written into a temporary sibling staging directory, and only
// on success is the staged tree swapped in. On Windows a directory swap is
// two renames (old -> backup, staged -> out) with a small gap; it is not
// strictly atomic. If publish fails after the old output was moved, the
// renderer tries to roll back by renaming the backup back to the original
// path. If rollback also fails, the backup directory is preserved next to
// outDir so no previously published content is lost. After a successful
// publish only the backup that render created is removed (older backups are
// never scanned or deleted), and only after re-verifying via lstat that it is
// a real directory, never a link — a cleanup failure is reported with its
// path and never rolls back or deletes the new output. outDir itself must be
// absent or a real directory: a junction/symlink (live or dangling —
// existsSync alone misses the dangling case) or any other non-directory is
// refused before any output or link target is touched. Concurrent renderers
// are excluded by an exclusive lock directory per outDir; the lock is
// fail-closed (no automatic stale removal, no indefinite wait).
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, renameSync, lstatSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { parseFrontmatter } from '../../../lib/agents.mjs';
import { accessOf, piToolsForAccess } from '../../../lib/orchestrator/permissions.mjs';

// Parent-approved scope: only these subagent worker roles receive
// tool/provider completion (ludi_exec + shell-gate provider). All other roles
// keep their authored tools/frontmatter and never gain a provider.
export const SHELL_PROFILE_ROLES = new Set(['coder', 'tester']);

const joinLines = (...lines) => lines.join('\n') + '\n';

/**
 * Render the policy-explicit shell-gate wrapper for one derived profile.
 * Config is fixed JSON carrying the role's immutable access; the provider
 * registers exactly the ludi_exec tool through createShellGate — raw
 * powershell/bash are never granted on this path either.
 */
// Both distributed generated/agent-profiles and legacy out/agent-profiles
// have this depth. A relative module specifier survives moving/updating the kit.
export function renderProfileShellGate({ agent, shell, network }) {
  const config = { agent, shell, network: network === true };
  return joinLines(
    '// Generated by ludi-agent-kit native agent profiles. Config is fixed JSON; do not edit.',
    `import { createShellGate } from "../../../shell-gate/index.js";`,
    `const CONFIG = ${JSON.stringify(config)};`,
    'export default function ludiProfileShellGate(pi) {',
    '  createShellGate({ shell: CONFIG.shell, network: CONFIG.network })(pi);',
    '}',
  );
}

/**
 * Build the derived profile Markdown for one parsed agent definition.
 * Returns { fileName, agent, access, tools, extensionFileName|null, text }.
 * Only coder/tester are adapted: their `tools` is rewritten to the
 * access-derived allowlist (adding ludi_exec) and a shell-gate provider is
 * attached. All other roles return their source frontmatter untouched —
 * tools pass through verbatim and extensionFileName is null.
 */
export function deriveProfile(agent) {
  const meta = { ...(agent.meta ?? {}) };
  const name = String(meta.name ?? 'agent');
  const access = accessOf(agent);
  const adapted = SHELL_PROFILE_ROLES.has(name);
  const tools = adapted ? piToolsForAccess(access)
    : String(meta.tools ?? '').split(',').map(s => s.trim()).filter(Boolean);
  const extensionFileName = adapted && access.shell !== 'false' ? `${name}-shell-gate.mjs` : null;

  // Serialize frontmatter: keep every original key in order; `tools` is
  // rewritten only for adapted roles and `subagentOnlyExtensions` is appended
  // for them alone. Other fields (model-free routing, inheritance flags,
  // acceptance) pass through unchanged. Plain scalars stay plain — the shared
  // flat frontmatter parser treats the whole tail as the value, so JSON-style
  // quoting would survive literally. Strings that the flat parser cannot
  // delimit (embedded newlines, edge whitespace, comment starts) are an
  // authoring error: refuse rather than emit a frontmatter the two parsers
  // would read differently.
  const scalar = value => {
    if (typeof value === 'boolean' || typeof value === 'number') return ` ${value}`;
    const s = String(value);
    if (/[\r\n]|^\s|\s$|#/.test(s) || /^(?:true|false|-?\d+)$/i.test(s) || s === '') {
      // Embedded newlines/edge space/# cannot be delimited flat; true/false/digits
      // would silently re-type through the flat scalar parser.
      throw new Error(`agent profile frontmatter value is not a flat scalar: ${JSON.stringify(s)}`);
    }
    return ` ${s}`;
  };
  const lines = ['---'];
  // `tools` is always re-serialized (verbatim content for non-adapted roles);
  // `subagentOnlyExtensions` is regenerated for adapted roles and passes
  // through unchanged for every other role.
  const handled = new Set(['tools', 'subagentOnlyExtensions']);
  for (const [key, value] of Object.entries(meta)) {
    if (handled.has(key)) continue;
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
      lines.push(`${key}:`);
      for (const [k, v] of Object.entries(value)) lines.push(`  ${k}:${scalar(v)}`);
    } else {
      lines.push(`${key}:${scalar(value)}`);
    }
  }
  lines.push(`tools: ${tools.join(', ')}`);
  const extensionsLine = extensionFileName ? `./extensions/${extensionFileName}` : meta.subagentOnlyExtensions;
  if (extensionsLine) lines.push(`subagentOnlyExtensions:${scalar(extensionsLine)}`);
  lines.push('---');

  const body = String(agent.body ?? '').trim();
  const text = joinLines(lines.join('\n'), '', body);
  return { fileName: agent.file ?? `${name}.md`, agent: name, access, tools, extensionFileName, text };
}

function uniqueSuffix() {
  return `${process.pid}-${Date.now()}-${Math.random().toString(36).slice(2, 10)}`;
}

function siblingPath(base, tag) {
  return `${base}.${tag}-${uniqueSuffix()}`;
}

/**
 * Acquire an exclusive lock for outDir. Fails closed: if the lock directory
 * already exists the renderer refuses rather than waiting or deleting it.
 * Returns a release function.
 */
function acquireOutDirLock(outDir) {
  const lockDir = `${outDir}.lock`;
  try {
    mkdirSync(lockDir);
  } catch (e) {
    if (e.code === 'EEXIST') {
      throw new Error(`agent profiles outDir is locked by another renderer: ${lockDir}`);
    }
    throw e;
  }
  return () => {
    rmSync(lockDir, { recursive: true, force: true });
  };
}

/**
 * Classify the outDir entry itself via lstat so a junction/symlink is seen as
 * the link, not its target. Returns null when nothing exists. Distinguishes
 * 'directory' (a real directory — a link to a directory reports 'symlink'
 * instead), 'symlink' (live or dangling link/junction), 'file', and 'other'.
 */
function describeOutDirEntry(outDir) {
  let st;
  try {
    st = lstatSync(outDir);
  } catch (e) {
    if (e.code === 'ENOENT') return null;
    throw e;
  }
  if (st.isSymbolicLink()) return 'symlink';
  if (st.isDirectory()) return 'directory';
  if (st.isFile()) return 'file';
  return 'other';
}

/**
 * Enforce the publish boundary: outDir must be absent or a real directory.
 * Anything else (junction/symlink — live or dangling, regular file, other
 * non-directory) is refused with the path before any output content or link
 * target is touched. A stale `*.lock` from a previous refusal does not count
 * as outDir existing.
 */
function assertWritableOutDir(outDir) {
  const kind = describeOutDirEntry(outDir);
  if (kind === null || kind === 'directory') return;
  const why = kind === 'symlink'
    ? 'a junction/symlink (live or dangling) — refusing to write through or replace it'
    : `a non-directory entry (${kind})`;
  throw new Error(`agent profiles outDir must be absent or a real directory; found ${why}: ${outDir}`);
}

function listMarkdownFiles(dir) {
  return readdirSync(dir).filter(f => f.endsWith('.md') && f !== 'README.md').sort();
}

function listExtensionFiles(dir) {
  return readdirSync(dir).filter(f => f.endsWith('.mjs')).sort();
}

/**
 * Generate all derived profiles + their shell-gate providers into outDir.
 * Reads every common agent file from agentsDir; writes <outDir>/<name>.md and,
 * for adapted shell-capable roles, <outDir>/extensions/<name>-shell-gate.mjs.
 * Returns an array of per-agent records.
 *
 * The renderer owns outDir wholesale but does not delete existing content up
 * front: it stages every output under a temporary sibling directory first,
 * then swaps it in only after all files are written successfully. Existing
 * profiles and providers therefore survive parse/derive/write failures. A
 * stale role is still removed — but only when its replacement is already
 * fully staged. An exclusive lock directory serializes concurrent renderers.
 */
export function renderAgentProfiles({ agentsDir, outDir, writeImpl = writeFileSync, renameImpl = renameSync, rmImpl = rmSync } = {}) {
  mkdirSync(dirname(outDir), { recursive: true });
  assertWritableOutDir(outDir);
  const release = acquireOutDirLock(outDir);
  const stagingDir = siblingPath(outDir, 'staging');
  const backupDir = siblingPath(outDir, 'backup');
  let published = false;
  let createdBackup = null;
  try {
    // 1) Parse + derive every candidate before touching the live output.
    const profiles = [];
    for (const file of listMarkdownFiles(agentsDir)) {
      const source = parseFrontmatter(readFileSync(join(agentsDir, file), 'utf8'));
      source.file = file;
      profiles.push(deriveProfile(source));
    }

    // 2) Write the complete new generation into a private staging dir.
    mkdirSync(stagingDir, { recursive: true });
    mkdirSync(join(stagingDir, 'extensions'), { recursive: true });
    for (const p of profiles) {
      writeImpl(join(stagingDir, p.fileName), p.text);
      if (p.extensionFileName) {
        writeImpl(join(stagingDir, 'extensions', p.extensionFileName),
          renderProfileShellGate({ agent: p.agent, shell: p.access.shell, network: p.access.network }));
      }
    }

    // 3) Publish. On Windows this is two renames and is not strictly atomic;
    //    a failed swap rolls the previous output back if possible. Re-verify
    //    the outDir boundary here too: a link swapped in between step 1 and
    //    the swap must never be renamed into our backup or written through.
    const hadOutDir = describeOutDirEntry(outDir) === 'directory';
    if (!hadOutDir) assertWritableOutDir(outDir);
    if (hadOutDir) {
      renameImpl(outDir, backupDir);
      createdBackup = backupDir;
    }
    try {
      renameImpl(stagingDir, outDir);
      published = true;
    } catch (publishError) {
      if (hadOutDir) {
        try {
          renameImpl(backupDir, outDir);
        } catch (rollbackError) {
          // Leave the backup in place and surface both failures so the old
          // published output is never silently lost.
          throw new Error(
            `agent profiles publish failed: ${publishError.message}; ` +
            `rollback also failed: ${rollbackError.message}. ` +
            `Previous output preserved at ${backupDir}`
          );
        }
      }
      throw publishError;
    }
    // 4) Successful publish: remove only the backup this render created so
    //    consecutive renders do not accumulate backup-* dirs. Older backups
    //    are never scanned or touched. The path is re-verified as a real
    //    directory first — if it were a link we must not recurse into it, and
    //    if it is gone or not a directory there is nothing of ours to delete.
    //    A cleanup failure never rolls back or deletes the new output; it is
    //    surfaced as a diagnostic naming the exact leftover path.
    if (createdBackup) {
      const leftover = describeOutDirEntry(createdBackup) === 'directory' ? createdBackup : null;
      if (leftover) {
        try {
          rmImpl(leftover, { recursive: true, force: true });
        } catch (cleanupError) {
          throw new Error(
            `agent profiles published successfully but failed to remove the superseded backup at ${leftover}: ${cleanupError.message}. ` +
            'New output is live; remove the leftover directory manually.'
          );
        }
      }
    }
    return profiles.map(p => ({ file: p.fileName, agent: p.agent, access: p.access, tools: p.tools, extension: p.extensionFileName }));
  } finally {
    // Only the renderer-owned staging directory is cleaned up. The published
    // directory and any preserved backup are left for diagnosis. The lock is
    // released unconditionally.
    if (!published) {
      try { rmSync(stagingDir, { recursive: true, force: true }); } catch { /* best effort */ }
    }
    release();
  }
}
