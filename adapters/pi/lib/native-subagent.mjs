// Native in-process subagent launcher for the Pi-hosted orchestrator.
//
// Uses the documented public pi-subagents event contracts only — no internal
// imports, no dependency on a separately installed package, and never the
// model-facing `subagent` tool:
//   - `pi-subagents:runtime-agent-register:v1` registers one uniquely named
//     runtime agent per invocation (synchronous; `request.result` is written by
//     the owner before emit returns; a missing result means no owner).
//   - `prompt-template:subagent:request` / `:started` / `:update` / `:response`
//     / `:cancel` run one foreground structured delegation (fresh context).
//
// Guarantees kept from the subprocess launcher (adapters/pi/lib/subagent.mjs):
//   - pinned model per attempt (per-run `model` wins over definition settings)
//   - explicit tool allowlist incl. a hidden guard sentinel tool, hard
//     turn/tool caps enforced child-side by the generated guard extension
//     (stricter initial caps; no adapter-local progress extension),
//     `extensions:[]` so ambient/configured extensions never load, and shell
//     access only through the gated `ludi_exec` tool
//   - sanitized progress events only (tool name — never args or output)
//   - runtime/turn/tool bounds, real metrics (missing stays absent, never 0)
//   - exact-tuple cancel on caller abort/deadline; on an unconfirmed stop the
//     result carries `retainWorkspaceUntil` so the caller's writer lease stays
//     held until matching terminal AND guard quiescence; host death needs manual recovery.
//
// An absent owner is reported pre-dispatch (`unavailable: true`) so the host may
// choose the subprocess launcher once. There is NO fallback after dispatch,
// after cancel, or after failure — anything else is terminal.
import { mkdtempSync, writeFileSync, readFileSync, rmSync, watch, lstatSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve, isAbsolute } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { realpathSync } from 'node:fs';
import { randomUUID, randomBytes } from 'node:crypto';
import { GUARD_TOOL } from './native-guard.mjs';

const __dir = dirname(realpathSync(fileURLToPath(import.meta.url)));
const shellGatePath = resolve(__dir, '..', 'shell-gate', 'index.js');
const nativeGuardPath = resolve(__dir, 'native-guard.mjs');

export const RUNTIME_AGENT_REGISTER_EVENT = 'pi-subagents:runtime-agent-register:v1';
export const DELEGATION_REQUEST_EVENT = 'prompt-template:subagent:request';
export const DELEGATION_STARTED_EVENT = 'prompt-template:subagent:started';
export const DELEGATION_UPDATE_EVENT = 'prompt-template:subagent:update';
export const DELEGATION_RESPONSE_EVENT = 'prompt-template:subagent:response';
export const DELEGATION_CANCEL_EVENT = 'prompt-template:subagent:cancel';

// How long to wait for the authoritative terminal event after sending cancel.
const CANCEL_GRACE_MS = 15000;
const THINKING_LEVELS = new Set(['off', 'minimal', 'low', 'medium', 'high', 'xhigh', 'max']);
const TERMINAL_STATUSES = new Set(['completed', 'failed', 'timed_out', 'cancelled', 'interrupted',
  'tool_budget_exhausted', 'structured_output_failed', 'acceptance_failed', 'invalid_request',
  'unavailable_context', 'duplicate_node']);
// Tools this launcher never grants, even if requested.
const ALLOWED_TOOLS = new Set(['read', 'grep', 'find', 'ls', 'edit', 'write', 'ludi_exec']);

function sanitizeName(value) {
  return String(value ?? 'agent').replace(/[^A-Za-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 96) || 'agent';
}

/** Strip a trailing `:<thinking>` from a "provider/model[:thinking]" id. */
function stripThinking(modelId) {
  const text = String(modelId ?? '');
  const i = text.lastIndexOf(':');
  if (i > 0 && THINKING_LEVELS.has(text.slice(i + 1))) return { model: text.slice(0, i), thinking: text.slice(i + 1) };
  return { model: text, thinking: undefined };
}

/** Render the per-launch guard wrapper extension: kit imports + JSON config only. */
export function renderGuardModule({ maxTurns, maxToolCalls, allowedTools, shell, network, sidecarPath }) {
  const config = {
    guard: { maxTurns, maxToolCalls, allowedTools: [...allowedTools], sidecarPath: sidecarPath ?? null },
    shell: { shell, network: network === true, requireConfirmedExit: true },
  };
  return `// Generated by ludi-agent-kit native launcher. Config is fixed JSON; do not edit.
import { createNativeGuard } from ${JSON.stringify(pathToFileURL(nativeGuardPath).href)};
import { createShellGate } from ${JSON.stringify(pathToFileURL(shellGatePath).href)};
const CONFIG = ${JSON.stringify(config)};
export default function ludiNativeGuard(pi) {
  createNativeGuard(CONFIG.guard)(pi);
  if (CONFIG.shell.shell !== 'false') createShellGate(CONFIG.shell)(pi);
}
`;
}

/** Preflight a request BEFORE any registration or dispatch. Returns an error string or null. */
function validateRequest(req) {
  if (req.signal?.aborted) return 'caller signal already aborted before launch';
  const limits = req.limits ?? {};
  // Present-but-malformed bounds refuse; absent bounds take the documented defaults.
  if (limits.max_turns !== undefined && !(Number.isSafeInteger(limits.max_turns) && limits.max_turns > 0))
    return `limits.max_turns must be a positive safe integer, got ${JSON.stringify(limits.max_turns)}`;
  if (limits.max_tool_calls !== undefined && !(Number.isSafeInteger(limits.max_tool_calls) && limits.max_tool_calls >= 0))
    return `limits.max_tool_calls must be a non-negative safe integer, got ${JSON.stringify(limits.max_tool_calls)}`;
  if (limits.max_runtime_ms !== undefined && !(Number.isSafeInteger(limits.max_runtime_ms) && limits.max_runtime_ms > 0 && limits.max_runtime_ms <= 2147483647))
    return `limits.max_runtime_ms must be a positive safe integer, got ${JSON.stringify(limits.max_runtime_ms)}`;
  const modelId = req.modelId;
  if (typeof modelId !== 'string' || !/^[^\s/:]+\/\S+$/.test(modelId)) return `modelId must be "provider/model[:thinking]", got ${JSON.stringify(modelId)}`;
  // Model IDs are opaque and may themselves contain ':' or '/'. Only a known
  // trailing thinking level is interpreted by the documented Pi selector syntax.
  if (typeof req.cwd !== 'string' || !req.cwd || !isAbsolute(req.cwd)) return `cwd must be an absolute path, got ${JSON.stringify(req.cwd)}`;
  if (!Array.isArray(req.toolNames)) return 'toolNames must be an array';
  for (const tool of req.toolNames) {
    if (typeof tool !== 'string' || !tool) return `toolNames entries must be non-empty strings, got ${JSON.stringify(tool)}`;
    if (!ALLOWED_TOOLS.has(tool)) return `tool "${tool}" can never be granted by this launcher`;
    if (tool === 'ludi_exec' && (req.access?.shell ?? 'false') === 'false') return 'tool "ludi_exec" requires access.shell other than false';
    if ((tool === 'edit' || tool === 'write') && req.access?.filesystem !== 'read-write') return `tool "${tool}" requires access.filesystem "read-write"`;
  }
  if (req.access?.filesystem === 'read-write' && typeof req.protectWorkspace !== 'function')
    return 'native writes require a caller-owned protected workspace lease';
  if (typeof req.prompt !== 'string' || !req.prompt) return 'prompt must be a non-empty string';
  return null;
}

/** True when every usage field present is a finite non-negative number. */
function validUsage(usage) {
  if (usage == null) return true;
  if (typeof usage !== 'object' || Array.isArray(usage)) return false;
  return ['input', 'output', 'cacheRead', 'cacheWrite', 'cost', 'turns', 'toolCalls', 'durationMs']
    .every(key => usage[key] === undefined || (typeof usage[key] === 'number' && Number.isFinite(usage[key]) && usage[key] >= 0));
}

/**
 * Map a terminal delegation response to the runner result shape.
 * Metrics are copied only when present — absent stays absent (never 0).
 * Every post-admission non-completed status aborts the task: no candidate retry.
 */
function terminalResult(response, req, child) {
  const usage = validUsage(response.usage) ? response.usage : null;
  if (usage) {
    if (usage.turns !== undefined) child.turns = usage.turns;
    if (usage.toolCalls !== undefined) child.toolCalls = usage.toolCalls;
    if (usage.durationMs !== undefined) child.durationMs = usage.durationMs;
  }
  const status = response.status;
  const error = response.error;
  if (status === 'completed') {
    const text = response.result?.kind === 'text' && typeof response.result.text === 'string' ? response.result.text : undefined;
    if (text == null) {
      return { ok: false, abort: true, error: 'native delegation completed without a text result', failureClass: 'EMPTY_RESPONSE' };
    }
    return { ok: true, text };
  }
  // Post-admission: every failure is terminal — abort, never a model retry.
  const failureClass =
    status === 'timed_out' ? 'TIMEOUT'
    : status === 'tool_budget_exhausted' ? 'TOOL_BUDGET_EXHAUSTED'
    : status === 'structured_output_failed' ? 'MALFORMED_RESULT'
    : 'UNKNOWN';
  const out = { ok: false, abort: true, error: error ?? `native delegation ${status}`, failureClass };
  if (status === 'tool_budget_exhausted') child.stopReason = 'tool-call-limit';
  if (status === 'timed_out') child.stopReason = 'native-timeout';
  if (status === 'cancelled' || status === 'interrupted') child.stopReason = 'cancelled';
  return out;
}

/**
 * Create the native runner bound to the extension's `pi` object.
 * @param {object} opts.pi          ExtensionAPI (uses pi.events only)
 * @param {number} [opts.cancelGraceMs] bounded wait for terminal after cancel
 */
export function createNativeSubagentRunner({ pi, cancelGraceMs = CANCEL_GRACE_MS } = {}) {
  if (!pi?.events || typeof pi.events.emit !== 'function' || typeof pi.events.on !== 'function') {
    throw new Error('native subagent runner requires the pi extension object (pi.events)');
  }
  const events = pi.events;
  const active = new Set(); // attempts in flight; survives dispose until proof
  let disposed = false;
  let seq = 0;

  // A structured terminal can follow a forced native finish while a tool is
  // still running. Require independent guard quiescence as well. Missing/stale
  // evidence never releases the lease, even after an exact terminal.
  function quiescence(attempt) {
    if (attempt.quietPromise) return attempt.quietPromise;
    attempt.quietPromise = new Promise(resolveQuiet => {
      if (!attempt.started && ['invalid_request', 'unavailable_context', 'duplicate_node', 'cancelled'].includes(attempt.terminal?.status)) {
        resolveQuiet({ rejectedBeforeStart: true }); return;
      }
      const inspect = () => {
        try {
          const state = JSON.parse(readFileSync(attempt.sidecarPath, 'utf8'));
          if (state.version === 1 && state.shutdown === true && state.pendingTools === 0) {
            resolveQuiet(state); return true;
          }
        } catch { /* unknown is not quiescent */ }
        return false;
      };
      if (inspect()) return;
      try {
        const watcher = watch(attempt.guardDir, { persistent: false }, inspect);
        watcher.on('error', () => {}); // retain until host death if evidence disappears
        attempt.unsubscribes.push(() => watcher.close());
        inspect(); // cover a change between the first read and watch setup
      } catch { /* no safe proof: keep this promise pending */ }
    });
    return attempt.quietPromise;
  }

  /** Release after a known pre-start refusal, or terminal AND guard quiescence. */
  function releaseAttempt(attempt) {
    for (const t of attempt.timers.splice(0)) clearTimeout(t);
    for (const off of attempt.unsubscribes.splice(0)) { try { off(); } catch { /* best-effort */ } }
    try { attempt.registration?.dispose?.(); } catch { /* idempotent */ }
    if (attempt.guardDir) { try { rmSync(attempt.guardDir, { recursive: true, force: true }); } catch { /* best-effort */ } }
    active.delete(attempt);
  }
  /** Lightweight cleanup for attempts that never reached dispatch. */
  function releasePreDispatch(attempt) {
    for (const t of attempt.timers.splice(0)) clearTimeout(t);
    try { attempt.registration?.dispose?.(); } catch { /* no child was dispatched */ }
    if (attempt.guardDir) { try { rmSync(attempt.guardDir, { recursive: true, force: true }); } catch { /* best-effort */ } }
    active.delete(attempt);
  }

  async function runSubagent(req) {
    const child = {
      taskId: req?.taskId ?? null, runId: req?.runId ?? null, agent: req?.agent ?? null,
      modelId: req?.modelId ?? null, backend: req?.backend ?? null,
      startedAt: new Date().toISOString(), finishedAt: null, status: 'running', stopReason: null,
      transport: 'native', childSessionId: null, turns: null, toolCalls: null,
      native: null,
    };
    if (disposed) return { ok: false, error: 'native runner is disposed', failureClass: 'TOOL_FAILURE', abort: true, transport: 'native', child };
    const refused = validateRequest(req ?? {});
    if (refused) return { ok: false, error: `native launch refused: ${refused}`, failureClass: 'TOOL_FAILURE', abort: true, transport: 'native', child };

    const limits = req.limits ?? {};
    // Stricter initial caps: the native path enforces the resolved initial
    // budget directly; there is no adapter-local progress extension here.
    const maxTurns = limits.max_turns ?? 12;
    const maxToolCalls = limits.max_tool_calls ?? 40;
    const runtimeMs = limits.max_runtime_ms ?? 600000;
    const allowedTools = [...req.toolNames, GUARD_TOOL];
    const access = req.access ?? {};
    const requestId = `ludi-${randomUUID()}`;
    const ownerRunId = String(req.runId ?? 'ludi-native');
    const nodeId = `${sanitizeName(req.taskId)}-${++seq}`;
    const agentName = `ludi-${sanitizeName(req.agent)}-${randomBytes(4).toString('hex')}`;
    const emit = (type, data = {}) => { try { req.onEvent?.(type, data); } catch { /* telemetry never breaks a child */ } };
    child.native = { requestId, ownerRunId, nodeId, agent: agentName, runId: null };

    const attempt = {
      key: { requestId, ownerRunId, nodeId },
      registration: null, guardDir: null,
      unsubscribes: [], timers: [],
      terminal: null, terminalResolve: null, cancelled: false, started: false,
      notifyCancel: null, dispatched: false, quietPromise: null, sidecarPath: null,
    };
    attempt.terminalPromise = new Promise(resolve => { attempt.terminalResolve = resolve; });
    active.add(attempt);
    const cancelNotified = new Promise(resolve => { attempt.notifyCancel = resolve; });

    const sendCancel = () => {
      if (attempt.terminal || attempt.cancelled) return;
      attempt.cancelled = true;
      try { events.emit(DELEGATION_CANCEL_EVENT, { requestId, ownerRunId, nodeId }); }
      catch { /* an emit failure must not fabricate a stop confirmation */ }
      attempt.notifyCancel();
    };
    const wait = (ms, value) => new Promise(resolve => {
      const t = setTimeout(() => resolve(value), ms);
      attempt.timers.push(t);
    });
    const onAbort = () => sendCancel();
    const signal = req.signal;

    // --- pre-dispatch: generated guard extension ----------------------------
    let sidecarPath;
    try {
      attempt.guardDir = mkdtempSync(join(tmpdir(), 'ludi-native-'));
      sidecarPath = join(attempt.guardDir, 'guard-stop.json');
      attempt.sidecarPath = sidecarPath;
      writeFileSync(join(attempt.guardDir, 'index.mjs'), renderGuardModule({
        maxTurns, maxToolCalls, allowedTools,
        shell: access.shell ?? 'false', network: access.network === true,
        sidecarPath,
      }), { mode: 0o600 });
    } catch (error) {
      releasePreDispatch(attempt);
      return { ok: false, abort: true, transport: 'native', child,
        failureClass: 'TOOL_FAILURE', error: `native guard preparation failed: ${error.message}` };
    }

    // --- runtime agent registration (pre-dispatch; synchronous) -------------
    const { model: requestedModel, thinking } = stripThinking(req.modelId);
    const registrationRequest = {
      version: 1,
      name: agentName,
      definition: {
        description: `ludi orchestration child for task ${sanitizeName(req.taskId)}`,
        systemPrompt: req.systemPrompt,
        tools: allowedTools,
        // Deny ambient/configured extension inheritance; only this launch's
        // generated guard is supplied, child-side only.
        extensions: [],
        subagentOnlyExtensions: [join(attempt.guardDir, 'index.mjs')],
        allowNestedSubagents: false,
        inheritProjectContext: false,
        inheritGlobalContext: false,
        inheritSkills: false,
        defaultContext: 'fresh',
        defaultTimeoutMs: runtimeMs,
        toolBudget: { hard: maxToolCalls, block: '*' },
      },
    };
    try { events.emit(RUNTIME_AGENT_REGISTER_EVENT, registrationRequest); }
    catch (error) {
      attempt.registration = registrationRequest.result?.registration;
      releasePreDispatch(attempt);
      child.finishedAt = new Date().toISOString(); child.status = 'failed';
      return { ok: false, error: `runtime agent registration threw: ${error.message}`, failureClass: 'TOOL_FAILURE', abort: true, transport: 'native', child };
    }
    if (!registrationRequest.result) {
      // No compatible owner — BEFORE dispatch; the host may pick subprocess once.
      releasePreDispatch(attempt);
      child.finishedAt = new Date().toISOString(); child.status = 'failed';
      return { ok: false, error: 'pi-subagents runtime-agent owner is not installed or not ready', failureClass: 'UNKNOWN', unavailable: true, transport: 'native', child };
    }
    if (registrationRequest.result.ok === false) {
      // Explicit owner rejection is terminal — never fall back after admission.
      releasePreDispatch(attempt);
      child.finishedAt = new Date().toISOString(); child.status = 'failed';
      return { ok: false, error: `runtime agent registration rejected: ${registrationRequest.result.error?.message ?? registrationRequest.result.error}`, failureClass: 'TOOL_FAILURE', abort: true, transport: 'native', child };
    }
    attempt.registration = registrationRequest.result.registration;

    const matches = payload => payload && payload.requestId === requestId
      && payload.ownerRunId === ownerRunId && payload.nodeId === nodeId;
    const onStarted = payload => {
      if (!matches(payload)) return;
      attempt.started = true;
      emit('invocation-started', { transport: 'native' });
    };
    const onUpdate = payload => {
      if (!matches(payload) || attempt.terminal) return;
      if (payload.runId) { attempt.runId = payload.runId; child.native.runId = payload.runId; child.childSessionId = payload.runId; }
      // Sanitized: tool name only — never currentToolArgs/recentOutput/recentTools args.
      if (payload.currentTool) emit('invocation-tool', { tool: { name: payload.currentTool } });
      const turns = payload.usage?.turns;
      const toolCalls = payload.toolCount;
      if (turns != null || toolCalls != null) {
        if (turns != null) child.turns = turns;
        if (toolCalls != null) child.toolCalls = toolCalls;
        emit('invocation-turn', { turn: turns ?? undefined, turnCap: maxTurns, toolCalls: toolCalls ?? undefined });
      }
    };
    const onResponse = payload => {
      if (attempt.terminal) return;
      // Exact full-tuple correlation only. Our outgoing identity fields are all
      // valid, so even an `invalid_request` response must carry the complete
      // tuple; a foreign or partial payload can never settle this attempt.
      if (!matches(payload)) return;
      if (!TERMINAL_STATUSES.has(payload.status)) return;
      attempt.terminal = payload;
      if (payload.runId) { attempt.runId = payload.runId; child.native.runId = payload.runId; child.childSessionId = payload.runId; }
      attempt.terminalResolve(payload);
    };
    const on = (name, fn) => { const off = events.on(name, fn); if (typeof off === 'function') attempt.unsubscribes.push(off); };
    on(DELEGATION_STARTED_EVENT, onStarted);
    on(DELEGATION_UPDATE_EVENT, onUpdate);
    on(DELEGATION_RESPONSE_EVENT, onResponse);

    // Attach the caller-abort listener BEFORE dispatch so a mid-dispatch abort
    // still sends the exact cancel.
    signal?.addEventListener?.('abort', onAbort, { once: true });
    if (signal?.aborted || disposed) {
      signal?.removeEventListener?.('abort', onAbort);
      releaseAttempt(attempt);
      return { ok: false, abort: true, failureClass: 'UNKNOWN', transport: 'native', child,
        error: 'caller aborted during registration; no delegation dispatched' };
    }

    if (access.filesystem === 'read-write') {
      try { req.protectWorkspace(); }
      catch (error) {
        signal?.removeEventListener?.('abort', onAbort);
        releaseAttempt(attempt);
        return { ok: false, abort: true, transport: 'native', child, failureClass: 'TOOL_FAILURE',
          error: `native workspace protection failed before dispatch: ${error.message}` };
      }
    }
    const request = {
      requestId, ownerRunId, nodeId,
      agent: agentName,
      task: `${req.prompt}\n\nNATIVE_HANDOFF_BOUNDS\nHard limits: ${maxToolCalls} tool calls, ${maxTurns} turns. Whichever limit comes first applies. Reserve the final allowed turn for the final JSON result. When 3 turns remain or before the last 5 tool calls, stop exploration/new implementation and finalize from collected evidence. If work remains, return status partial, distinguishing verified work, failed/unverified checks and the next smallest task; never disguise unmet acceptance as completed. A warning is not extra budget. Automatic rules/native continuation is limited to read-only scout investigations with validated handoff evidence; a writer partial is saved for parent assessment, not automatically resumed or extended.\nContext Pack specification (outside the workspace): ${resolve(__dir, '../../../context-pack/SPEC.md')}. Read this exact path if needed; do not search the workspace for it.`,
      context: 'fresh',
      cwd: req.cwd,
      model: requestedModel,
      ...(thinking ? { thinking } : {}),
      timeoutMs: runtimeMs,
      toolBudget: { hard: maxToolCalls, block: '*' },
      skill: false,
      intercomBridge: { mode: 'off' },
      result: { kind: 'text' },
    };
    attempt.dispatched = true;
    emit('native-dispatch', { requestId, nodeId, agent: agentName });
    let emitError = null;
    try { events.emit(DELEGATION_REQUEST_EVENT, request); }
    catch (error) { emitError = error; }
    if (emitError) {
      // An earlier bus listener may already have admitted native execution;
      // treat the throw as uncertain admission: exact cancel, grace, retain.
      sendCancel();
    }

    let outcome = await Promise.race([
      attempt.terminalPromise.then(() => 'terminal'),
      wait(runtimeMs, 'deadline').then(v => { if (v === 'deadline') sendCancel(); return v; }),
      cancelNotified.then(() => 'cancel'),
    ]);
    if (outcome !== 'terminal' && !attempt.terminal) {
      // Deadline / caller cancel / uncertain emit: drain a bounded grace for
      // the authoritative terminal. Never a new attempt.
      outcome = await Promise.race([
        attempt.terminalPromise.then(() => 'terminal'),
        wait(cancelGraceMs, 'grace-expired'),
      ]);
    }
    signal?.removeEventListener?.('abort', onAbort);

    for (const timer of attempt.timers.splice(0)) clearTimeout(timer);
    const terminal = attempt.terminal;
    if (!terminal) {
      // Unconfirmed stop: NEVER retry or fall back. The response listener,
      // registration and temp guard stay installed until the matching late
      // terminal plus guard quiescence; the caller retains the writer lease for
      // the same duration. A rejected retention promise is not proof — the
      // terminal promise only resolves through onResponse, so it cannot reject.
      child.finishedAt = new Date().toISOString();
      child.status = 'unconfirmed';
      child.stopReason = 'unconfirmed-stop';
      const retainWorkspaceUntil = attempt.terminalPromise.then(() => quiescence(attempt)).then(() => releaseAttempt(attempt));
      return {
        ok: false, abort: true, transport: 'native', child,
        error: (emitError ? `delegation emit threw (${emitError.message}) and ` : '')
          + `native child ${requestId} did not confirm its terminal state within ${cancelGraceMs}ms; workspace retained until terminal and guard quiescence proof (host death requires operator recovery)`,
        failureClass: emitError ? 'TOOL_FAILURE' : 'TIMEOUT',
        unconfirmedStop: true,
        retainWorkspaceUntil,
      };
    }
    // The native owner may hard-finish cancellation before its tools settle.
    // A terminal is necessary but not sufficient for releasing workspace ownership.
    const quietPromise = quiescence(attempt);
    const quiet = await Promise.race([quietPromise, wait(cancelGraceMs, null)]);
    for (const timer of attempt.timers.splice(0)) clearTimeout(timer);
    if (!quiet) {
      child.status = 'unconfirmed'; child.stopReason = 'guard-quiescence-unconfirmed';
      child.finishedAt = new Date().toISOString();
      return { ok: false, abort: true, unconfirmedStop: true, transport: 'native', child,
        failureClass: 'TOOL_FAILURE',
        error: 'native terminal received but the child guard has not proved tool quiescence; workspace retained until proof; host death requires operator recovery',
        retainWorkspaceUntil: quietPromise.then(() => releaseAttempt(attempt)) };
    }
    const guardStop = typeof quiet.reason === 'string' ? quiet : null;
    child.guardQuiescent = true;
    child.terminalStatus = terminal.status;
    child.cancelRequested = attempt.cancelled || signal?.aborted === true || disposed;
    // Snapshot only this launch's fixed guard-owned file, before temp cleanup.
    // It is evidence, never an accepted result. Do not follow model-supplied paths.
    let savedOutput;
    try {
      const info = lstatSync(`${sidecarPath}.output`);
      if (info.isFile() && !info.isSymbolicLink() && info.size <= 1024 * 1024)
        savedOutput = readFileSync(`${sidecarPath}.output`, 'utf8');
    } catch { /* no final snapshot available */ }
    releaseAttempt(attempt);
    child.finishedAt = new Date().toISOString();
    child.status = terminal.status === 'completed' ? 'finished' : 'failed';
    if (guardStop) {
      child.stopReason = `guard-${guardStop.reason}`;
      if (Number.isFinite(guardStop.toolCalls) && guardStop.toolCalls >= 0) child.toolCalls = guardStop.toolCalls;
    }
    if (emitError) {
      // The emit threw yet a terminal arrived — admission succeeded anyway.
      // The response remains authoritative; surface the emit anomaly.
      emit('native-emit-anomaly', { error: emitError.message });
    }
    // Pinned-model proof: a reported model that differs from the request is refused.
    if (terminal.model && terminal.model !== requestedModel && terminal.model !== String(req.modelId)) {
      child.status = 'failed';
      return { ok: false, abort: true, terminal: true, transport: 'native', child,
        error: `native child ran on model "${terminal.model}" instead of pinned "${req.modelId}"; refusing to accept the result`,
        failureClass: 'MODEL_FAILURE' };
    }
    if (terminal.thinking && thinking && terminal.thinking !== thinking) {
      child.status = 'failed';
      return { ok: false, abort: true, terminal: true, transport: 'native', child,
        error: `native child ran with thinking "${terminal.thinking}" instead of pinned "${thinking}"; refusing to accept the result`,
        failureClass: 'MODEL_FAILURE' };
    }
    if (!validUsage(terminal.usage)) {
      child.status = 'failed';
      return { ok: false, abort: true, terminal: true, transport: 'native', child,
        error: 'native child reported malformed usage counters; refusing to accept the result',
        failureClass: 'UNKNOWN' };
    }
    const mapped = terminalResult(terminal, req, child);
    // `terminal` marks a post-admission outcome as final for the generic
    // runner: no candidate fallback or retry may reuse this native launch.
    mapped.terminal = true;
    // A tripped guard means the child was force-stopped: a "completed"
    // terminal afterwards must not be accepted as a finished task.
    if (guardStop) {
      mapped.ok = false;
      delete mapped.text;
      mapped.abort = true;
      child.status = 'failed';
      mapped.error = `native child stopped by launch guard (${guardStop.reason}); result not accepted`;
      mapped.failureClass = guardStop.reason === 'tool-not-allowed' ? 'TOOL_FAILURE'
        : guardStop.reason === 'tool-call-limit' ? 'TOOL_BUDGET_EXHAUSTED' : 'TIMEOUT';
    }
    if (!mapped.ok) {
      const text = savedOutput ?? (terminal.result?.kind === 'text' && typeof terminal.result.text === 'string'
        && Buffer.byteLength(terminal.result.text, 'utf8') <= 1024 * 1024 ? terminal.result.text : undefined);
      if (text?.trim()) mapped.partialHandoff = { status: 'unaccepted', source: savedOutput != null ? 'native-guard' : 'native-response', text };
    }
    if (terminal.status !== 'completed' && !child.stopReason) child.stopReason = terminal.status;
    return { ...mapped, transport: 'native', child,
      usage: terminal.usage ?? undefined,
      launchContractDigest: terminal.launchContractDigest ?? undefined,
      nativeRunId: terminal.runId ?? attempt.runId ?? undefined };
  }

  return {
    transport: 'native',
    runSubagent,
    /**
     * Host teardown: mark disposed (no new runs) and send exact-tuple cancels
     * through the SAME notification path so pending callers enter grace. The
     * response listener, registration and temp guard stay installed until a
     * matching terminal and guard quiescence prove the stop — dispose never destroys proof.
     */
    dispose() {
      disposed = true;
      for (const attempt of [...active]) {
        if (attempt.dispatched && !attempt.terminal) {
          attempt.cancelled = true;
          try { events.emit(DELEGATION_CANCEL_EVENT, { ...attempt.key }); }
          catch { /* an emit failure must not fabricate a stop confirmation */ }
          attempt.notifyCancel?.();
        }
      }
    },
    /** For tests/diagnostics: attempts still awaiting terminal/quiescence proof. */
    activeCount: () => active.size,
  };
}

/**
 * Host-side launcher: prefer the native runner; fall back to the subprocess
 * launcher ONLY when the runtime-agent owner is absent (pre-dispatch) AND the
 * caller has not aborted. After native admission there is never a fallback.
 */
export function createHostSubagentRunner({ native, subprocess }) {
  return async function runSubagent(req) {
    if (req?.signal?.aborted) {
      return { ok: false, error: 'caller signal aborted before launch', failureClass: 'UNKNOWN', abort: true, transport: 'none' };
    }
    if (native) {
      // A rejected/invalid launcher call cannot establish whether dispatch ran.
      // Never let a generic caller turn that uncertainty into candidate retries.
      const unknown = detail => ({ ok: false, abort: true, terminal: true,
        unconfirmedStop: true, transport: 'native', failureClass: 'TOOL_FAILURE',
        error: `native launcher state is uncertain: ${detail}; operator recovery required`,
        retainWorkspaceUntil: new Promise(() => {}) });
      let result;
      try { result = await native(req); }
      catch (error) { return unknown(error?.message ?? 'unexpected launcher error'); }
      if (result?.unavailable === true && !req?.signal?.aborted) {
        const fallback = await subprocess(req);
        return { ...fallback, transport: 'subprocess', transportFallback: 'no-native-owner' };
      }
      if (!result || typeof result.ok !== 'boolean') return unknown('malformed launcher result');
      return { ...result, transport: result.transport ?? 'native' };
    }
    const fallback = await subprocess(req);
    return { ...fallback, transport: 'subprocess' };
  };
}
